  /**
   * 16進カラーを乗算して高さに応じた陰影（擬似アンビエントオクルージョン）を作る
   */
  function shadeHex(hex, factor) {
    const num = parseInt(hex.slice(1), 16);
    const r = Math.min(255, Math.max(0, Math.round(((num >> 16) & 255) * factor)));
    const g = Math.min(255, Math.max(0, Math.round(((num >> 8) & 255) * factor)));
    const b = Math.min(255, Math.max(0, Math.round((num & 255) * factor)));
    return `rgb(${r}, ${g}, ${b})`;
  }

  /**
   * ASCIIスライス配列から、オフスクリーンCanvas群（通常版 / 陰影版 / 発光ハイライト版）を生成
   */
  function buildModel(def) {
    const numLayers = def.layers.length;
    const height = def.layers[0].length;
    const width = def.layers[0][0].length;

    const rawCanvases = [];
    const shadedCanvases = [];
    const flashCanvases = [];

    for (let z = 0; z < numLayers; z++) {
      const slice = def.layers[z];
      // 下の層ほど少し暗く、上の層ほど明るくすると立体感が際立つ
      const shadeFactor = numLayers <= 1 ? 1 : 0.68 + (z / (numLayers - 1)) * 0.38;

      const raw = document.createElement("canvas");
      raw.width = width;
      raw.height = height;
      const rCtx = raw.getContext("2d");

      const shaded = document.createElement("canvas");
      shaded.width = width;
      shaded.height = height;
      const sCtx = shaded.getContext("2d");

      const flash = document.createElement("canvas");
      flash.width = width;
      flash.height = height;
      const fCtx = flash.getContext("2d");

      for (let y = 0; y < height; y++) {
        const row = slice[y];
        for (let x = 0; x < width; x++) {
          const ch = row[x];
          const color = PALETTE[ch];
          if (!color) continue;

          rCtx.fillStyle = color;
          rCtx.fillRect(x, y, 1, 1);

          // 発光色や花の色は暗くしすぎない
          const isBright =
            ch === "c" || ch === "y" || ch === "m" || ch === "o" || ch === "f" || ch === "F";
          sCtx.fillStyle = isBright ? color : shadeHex(color, shadeFactor);
          sCtx.fillRect(x, y, 1, 1);

          fCtx.fillStyle = "#ffffff";
          fCtx.fillRect(x, y, 1, 1);
        }
      }

      rawCanvases.push(raw);
      shadedCanvases.push(shaded);
      flashCanvases.push(flash);
    }

    return {
      id: def.id,
      name: def.name,
      description: def.description,
      width,
      height,
      layerCount: numLayers,
      scale: def.scale,
      swayable: Boolean(def.swayable),
      swayAmount: def.swayAmount || 0,
      swayCurve: def.swayCurve || 1.7,
      rawCanvases,
      shadedCanvases,
      flashCanvases,
    };
  }

